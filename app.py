"""
Sky voice demo — CAI3303C team project (TTS + STT).

This web app is the "ears and brain" of Sky:
    page (index.html) -> Whisper speech-to-text -> FAQ answer (TF-IDF + cosine)
The "mouth" is NOT in this project. Speech is generated by the F5-TTS server
from the TTS assignment (01_Assignments\\TTS), which runs on port 5000.
This app forwards the page's voice requests to that server.

Run with Start-Demo.ps1, then open http://localhost:5001
"""
import hashlib
import os
import tempfile
import threading
import time
from pathlib import Path

import requests
from flask import Flask, Response, jsonify, redirect, request, send_file

from sky_voice_demo import TTS_URL, THRESHOLD, FAQMatcher, choose_answer, speech_to_text

HERE = Path(__file__).resolve().parent
HOST = os.getenv("SKY_HOST", "127.0.0.1")          # only this PC can reach the demo
PORT = int(os.getenv("SKY_PORT", "5001"))
WHISPER_MODEL = os.getenv("WHISPER_MODEL", "base")
AUDIO_TYPES = (".webm", ".wav", ".mp3", ".m4a", ".ogg", ".mp4", ".flac")
# Saved answers: fixed FAQ answers only need to be spoken by F5-TTS once.
SAVED_DIR = Path(os.getenv("SKY_SAVED_DIR", HERE / "saved_answers"))

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 25 * 1024 * 1024

matcher = FAQMatcher(HERE / "faq.json")
matcher_lock = threading.Lock()       # the matcher refits its vectorizer on every question
whisper_lock = threading.Lock()       # one transcription at a time
whisper_model = None


@app.errorhandler(413)
def upload_too_large(error):
    return jsonify(error="Audio uploads must be no larger than 25 MB."), 413


def answer_question(question, english, heard="en"):
    """Sky answers in English only for now: the F5-TTS voice model has no Spanish training."""
    started = time.monotonic()
    with matcher_lock:
        entry, matched, score = matcher.best_match(english)
    return {
        "question": question, "english": english, "language": "en", "spoken_language": heard,
        "answer": choose_answer(entry, score, "en"),
        "matched": matched, "score": round(score, 3), "threshold": THRESHOLD,
        "fallback": score < THRESHOLD,
        "answer_seconds": round(time.monotonic() - started, 3),
    }


# ------------------------------------------------------------------ pages
@app.get("/")
@app.get("/demo")
@app.get("/demo/")
def demo_page():
    return send_file(HERE / "index.html")


@app.get("/studio")
def voice_studio():
    # The voice studio belongs to the TTS assignment server.
    return redirect(f"{TTS_URL}/studio")


@app.get("/health")
def health():
    """The demo itself is up; also report whether the TTS server can be reached."""
    try:
        tts = requests.get(f"{TTS_URL}/health", timeout=3).json()
        tts_status = tts.get("status", "unknown")
        tts_model = tts.get("model")
    except (requests.RequestException, ValueError):
        tts_status, tts_model = "offline", None
    return jsonify(status="running", whisper_model=WHISPER_MODEL,
                   tts_url=TTS_URL, tts_status=tts_status, tts_model=tts_model)


# ------------------------------------------------------------------ answers
@app.post("/demo/answer")
def typed_answer():
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        return jsonify(error="Send a JSON object containing text."), 400
    text = payload.get("text")
    if not isinstance(text, str) or not text.strip() or len(text) > 2000:
        return jsonify(error="Enter a question between 1 and 2000 characters."), 400
    # Typed questions are matched as English; spoken audio is translated by Whisper.
    return jsonify(answer_question(text.strip(), text.strip()))


@app.post("/demo/transcribe")
def recorded_answer():
    global whisper_model
    upload = request.files.get("file")
    if upload is None or not upload.filename:
        return jsonify(error="Upload or record an audio file first."), 400
    suffix = Path(upload.filename).suffix.lower()
    if suffix not in AUDIO_TYPES:
        return jsonify(error="Use WAV, MP3, WebM, M4A, OGG, MP4, or FLAC audio."), 400
    if not whisper_lock.acquire(blocking=False):
        return jsonify(error="Sky is transcribing another recording. Try again shortly."), 429
    started = time.monotonic()
    try:
        with tempfile.TemporaryDirectory(prefix="sky-question-") as folder:
            path = Path(folder) / ("question" + suffix)
            upload.save(path)
            if not path.stat().st_size:
                return jsonify(error="The recording is empty. Please try another file."), 400
            import whisper
            if whisper_model is None:
                whisper_model = whisper.load_model(WHISPER_MODEL)   # uses the GPU if PyTorch has CUDA
            question, language, english = speech_to_text(whisper_model, str(path))
        if not question:
            return jsonify(error="No speech was recognized. Try a clearer recording."), 422
        result = answer_question(question, english, language)
        result["transcribe_seconds"] = round(time.monotonic() - started, 3)
        return jsonify(result)
    except ImportError:
        return jsonify(error="Whisper is not installed. Run Setup-Demo.ps1."), 503
    except Exception as error:
        return jsonify(error=f"Could not transcribe this recording: {str(error)[:500]}"), 422
    finally:
        whisper_lock.release()


# ------------------------------------------------------------------ voice
def saved_path(voice, text):
    """One WAV file per voice + answer text."""
    key = hashlib.sha1(f"{voice}\n{text}".encode("utf-8")).hexdigest()[:16]
    return SAVED_DIR / f"{key}.wav"


@app.post("/tts")
def speak():
    """Play a saved answer if there is one; otherwise ask the TTS server to generate it."""
    payload = request.get_json(silent=True)
    if not isinstance(payload, dict):
        return jsonify(error="A JSON object with username and text is required."), 400
    voice, text = payload.get("username"), payload.get("text")
    if isinstance(voice, str) and isinstance(text, str):
        saved = saved_path(voice, text)
        if saved.is_file():
            response = send_file(saved, mimetype="audio/wav")
            response.headers["X-Sky-Source"] = "saved"
            return response
    try:
        reply = requests.post(f"{TTS_URL}/tts", json=payload, timeout=600)
    except requests.RequestException:
        return jsonify(error=f"The TTS server at {TTS_URL} is not reachable. Start it with Start-TTS.ps1."), 503
    response = Response(reply.content, status=reply.status_code,
                        content_type=reply.headers.get("Content-Type", "application/octet-stream"))
    response.headers["X-Sky-Source"] = "generated"
    return response


@app.post("/demo/save_answer")
def save_answer():
    """Keep a generated WAV so the same answer plays instantly next time."""
    upload = request.files.get("file")
    voice, text = request.form.get("username", ""), request.form.get("text", "")
    if upload is None or not voice or not text or len(text) > 2000:
        return jsonify(error="Send the WAV file with its username and text."), 400
    data = upload.read()
    if len(data) < 44 or data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        return jsonify(error="Only WAV audio from F5-TTS can be saved."), 400
    SAVED_DIR.mkdir(parents=True, exist_ok=True)
    saved_path(voice, text).write_bytes(data)
    return jsonify(saved=True, count=len(list(SAVED_DIR.glob("*.wav"))))


@app.post("/demo/clear_saved")
def clear_saved():
    """Remove all saved answers, so F5-TTS generates them live again."""
    removed = 0
    if SAVED_DIR.is_dir():
        for wav in SAVED_DIR.glob("*.wav"):
            wav.unlink()
            removed += 1
    return jsonify(removed=removed)


if __name__ == "__main__":
    print(f"Sky demo: http://localhost:{PORT}  (TTS server: {TTS_URL})")
    app.run(host=HOST, port=PORT, threaded=True)
